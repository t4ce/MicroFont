#!/usr/bin/env python3
"""Index Unicode-named glyph bins with shared flipped glyph aliases for the line demo; run before make's Rust build."""
import argparse
import json
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ALIASES = {'9': ('6', 'Rotate180'), 'd': ('b', 'MirrorX'), 'q': ('p', 'MirrorX'), 'u': ('n', 'Rotate180'), 'f': ('t', 'MirrorY')}

def identifier(ch):
    return f'BINARY_{ord(ch):04X}'

def discover(folder):
    paths = {}
    for path in sorted(folder.glob('*.bin')):
        stem = path.stem
        if not re.fullmatch(r'u[0-9A-F]{4,6}', stem):
            raise ValueError(f'{path}: expected uXXXX.bin, lowercase u and uppercase hex')
        code = int(stem[1:], 16)
        if code > 0x10FFFF or 0xD800 <= code <= 0xDFFF:
            raise ValueError(f'{path}: not a Unicode scalar value')
        if path.name != f'u{code:04X}.bin':
            raise ValueError(f'{path}: use canonical name u{code:04X}.bin')
        ch = chr(code)
        paths[ch] = path
    return paths

def generate(folder, output):
    records = []
    declarations = []
    paths = discover(folder)
    for ch, path in sorted(paths.items(), key=lambda item: ord(item[0])):
        if ch in ALIASES:
            continue
        data = path.read_bytes()
        cursor = 0
        if not data:
            raise ValueError(f'{path}: empty glyph')
        while cursor < len(data):
            count = (data[cursor] & 63) + 2
            cursor += 1
            if count > len(data)-cursor:
                raise ValueError(f'{path}: truncated strip at byte {cursor-1}')
            for i in range(cursor,cursor+count):
                v=data[i]
                if v & 128 or v & 7 >= 6 or v >> 3 >= 11:
                    raise ValueError(f'{path}: invalid point 0x{v:02X} at byte {i}')
            cursor += count
        rel = json.dumps(os.path.relpath(path,output.parent))
        declarations.append(f"const {identifier(ch)}: &[Strip] = &decode_glyph::<{{ glyph_strip_count(include_bytes!({rel})) }}>(include_bytes!({rel}));")
        records.append(f"        '\\u{{{ord(ch):X}}}' => Some({identifier(ch)}),")
    for ch, (canonical, transform) in ALIASES.items():
        if canonical not in paths:
            continue
        source_name = identifier(canonical)
        declarations.append(f'const {identifier(ch)}: &[Strip] = &transformed_glyph::<{{ {source_name}.len() }}>({source_name}, GlyphTransform::{transform});')
        records.append(f"        '\\u{{{ord(ch):X}}}' => Some({identifier(ch)}),")
    source = '\n'.join([
        '// Generated by tools/generate_line_glyphs.py; add Unicode-named bins, then make iso.',
        *declarations,
        "const fn binary_glyph_strips(character: char) -> Option<&'static [Strip]> {",
        '    match character {', *records, '        _ => None,', '    }', '}', '',
    ])
    if not output.exists() or output.read_text() != source:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(source)
    return len(records)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input-dir',type=Path,default=ROOT/'data/line-v1')
    parser.add_argument('--output',type=Path,default=ROOT/'src/generated_line_glyphs.rs')
    args=parser.parse_args()
    try:
        count=generate(args.input_dir.resolve(),args.output.resolve())
    except ValueError as error:
        parser.exit(1,str(error)+'\n')
    print(f'microfont-line-glyphs: {count} Unicode glyphs indexed')

if __name__=='__main__':
    main()
