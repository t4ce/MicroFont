#!/usr/bin/env python3
"""Index present A.bin..Z.bin files for the line demo; run before make's Rust build."""
import argparse
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def generate(folder, output):
    records = []
    declarations = []
    for ch in 'ABCDEFGHIJKLMNOPQRSTUVWXYZ':
        path = folder / (ch + '.bin')
        if not path.exists():
            continue
        data = path.read_bytes()
        cursor = 0
        if not data:
            raise ValueError(f'{path}: empty glyph')
        while cursor < len(data):
            count = (data[cursor] & 63) + 2
            cursor += 1
            if count > len(data)-cursor:
                raise ValueError(f'{path}: truncated strip at byte {cursor-1}')
            for i in range(cursor,cursor+count):
                v=data[i]
                if v & 128 or v & 7 >= 6 or v >> 3 >= 11:
                    raise ValueError(f'{path}: invalid point 0x{v:02X} at byte {i}')
            cursor += count
        rel = json.dumps(os.path.relpath(path,output.parent))
        declarations.append(f"const BINARY_{ch}: &[Strip] = &decode_glyph::<{{ glyph_strip_count(include_bytes!({rel})) }}>(include_bytes!({rel}));")
        records.append(f"        '{ch}' => Some(BINARY_{ch}),")
    source = '\n'.join([
        '// Generated by tools/generate_line_glyphs.py; add letter bins, then make iso.',
        *declarations,
        "const fn binary_glyph_strips(character: char) -> Option<&'static [Strip]> {",
        '    match character {', *records, '        _ => None,', '    }', '}', '',
    ])
    if not output.exists() or output.read_text() != source:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(source)
    return len(records)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input-dir',type=Path,default=ROOT/'data/line-v1')
    parser.add_argument('--output',type=Path,default=ROOT/'src/generated_line_glyphs.rs')
    args=parser.parse_args()
    try:
        count=generate(args.input_dir.resolve(),args.output.resolve())
    except ValueError as error:
        parser.exit(1,str(error)+'\n')
    print(f'microfont-line-glyphs: {count}/26 uppercase glyphs indexed')

if __name__=='__main__':
    main()
