#[cfg(feature = "raster")]
pub(crate) const RASTER_SYMBOLS: [(char, u128); 128] = {
    let mut symbols = BOX_DRAW_SYMBOLS;
    let mut i = 0;
    while i < symbols.len() {
        if symbols[i].0 >= '╭' && symbols[i].0 <= '╳' { symbols[i].1 = 0; }
        i += 1;
    }
    symbols
};

#[cfg(feature = "raster")]
pub(crate) const fn diagonal_quads(character: char) -> &'static [crate::raster::BoxDrawQuad] {
    use crate::raster::BoxDrawQuad;
    const SLASH: BoxDrawQuad = BoxDrawQuad { vertices: [
        [5.0, 0.0], [6.0, 0.0], [1.0, 11.0], [0.0, 11.0],
    ] };
    const BACKSLASH: BoxDrawQuad = BoxDrawQuad { vertices: [
        [0.0, 0.0], [1.0, 0.0], [6.0, 11.0], [5.0, 11.0],
    ] };
    match character {
        '╱' => &[SLASH],
        '╲' => &[BACKSLASH],
        // Full backslash plus the two parts of the slash outside it. Their
        // angled cut edges meet the backslash exactly, without double shading.
        '╳' => &[
            BACKSLASH,
            BoxDrawQuad { vertices: [[5.0, 0.0], [6.0, 0.0], [3.5, 5.5], [3.0, 4.4]] },
            BoxDrawQuad { vertices: [[2.5, 5.5], [3.0, 6.6], [1.0, 11.0], [0.0, 11.0]] },
        ],
        _ => &[],
    }
}
