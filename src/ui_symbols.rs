pub(crate) fn glyph_cell_pixels(character: char) -> Option<u128> {
    GLYPHS.binary_search_by_key(&character, |&(code, _)| code)
        .ok().map(|index| GLYPHS[index].1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn all_ui_glyphs_reach_unicode_lookup() {
        for (index, &(ch, pixels)) in GLYPHS.iter().enumerate() {
            assert!(pixels > 0 && pixels < (1u128 << 66));
            assert!(index == 0 || GLYPHS[index - 1].0 < ch);
            assert_eq!(crate::glyph_cell_pixels(ch), pixels);
            assert_eq!(crate::measure_text(&std::format!("{ch}")), (6, 11));
        }
        assert_eq!(glyph_cell_pixels('A'), None);
    }

    #[test]
    fn unicode_stamping_preserves_revised_wastebasket() {
        let mut buffer = [0u8; 66];
        crate::stamp_text(&mut buffer, 6, 11, 0, 0, "🗑", 1).unwrap();
        let rows = ["......", ".###..", "#####.", "......", "#.#.#.",
            "#.#.#.", "#.#.#.", "#.#.#.", "#####.", "......", "......"];
        for (y, row) in rows.iter().enumerate() {
            for (x, pixel) in row.bytes().enumerate() {
                assert_eq!(buffer[y * 6 + x], u8::from(pixel == b'#'));
            }
        }
    }
}
